//! Runtime conditional responses for Plan trials, scoped to the loaded skill table.
use std::sync::Mutex;

use super::*;
use crate::manufacture::ManuOperator;
use crate::pool::n_choose_k_u64;

#[derive(Debug, Default)]
pub(crate) struct ManufactureSearchBake {
    tables: Mutex<Vec<ResponseTable>>,
}

#[derive(Debug)]
struct ResponseTable {
    operators: Vec<ManuOperator>,
    skills: Vec<SkillDef>,
    options: ManuSearchOptions,
    hits: Vec<ManuSearchHit>,
    masks: Vec<Vec<u64>>,
}

impl ManufactureSearchBake {
    pub(crate) fn search(
        &self,
        pool: &ManuPool,
        table: &SkillTable,
        options: &ManuSearchOptions,
    ) -> Result<ManuSearchReport> {
        // This cache owns only full-pool, static, single-room responses. Other
        // consumers retain the ordinary search and its persistent Bake gate.
        if !options.full_pool
            || options.shift_hours.is_some()
            || !matches!(options.recipe_mode, ManuSearchRecipeMode::Single(_))
        {
            return search_manufacture_triples(pool, table, options);
        }
        let started = Instant::now();
        let mut sub = filter_general_manufacture_search_pool(pool);
        if let Some(anchor) = options.must_include_name.as_deref() {
            if sub.entry(anchor).is_none() {
                if let Some(entry) = pool.entry(anchor) {
                    sub.entries.push(entry.clone());
                }
            }
            if sub.entry(anchor).is_none() {
                return search_manufacture_triples(pool, table, options);
            }
        }
        let operators: Vec<_> = sub
            .entries
            .iter()
            .map(|entry| entry.to_manu_operator())
            .collect();
        let layout = cache_layout(&options.layout, &operators, table);
        let mut tables = self
            .tables
            .lock()
            .unwrap_or_else(|error| error.into_inner());
        let cached = tables.iter().position(|cached| {
            cached.options.level == options.level
                && cached.options.operator_capacity == options.operator_capacity
                && cached.options.recipe_mode == options.recipe_mode
                && cached.options.mood == options.mood
                && cache_layout(&cached.options.layout, &operators, table) == layout
                && cached.skills == table.skills()
                && (cached.options.must_include_name.is_none()
                    || cached.options.must_include_name == options.must_include_name)
                // A subsequence preserves live enumeration's operator order,
                // including the comparator's final ordered-name tiebreak.
                && is_subsequence(&operators, &cached.operators)
        });
        if let Some(index) = cached {
            let mut perf =
                crate::profile::start_search_perf(crate::profile::SearchOperation::Manufacture);
            let report = tables[index].query(&operators, options, started);
            perf.finish(
                report.combinations,
                0,
                report.evaluated,
                report.top.len() as u64,
                true,
                crate::profile::SearchPhaseDurations {
                    bake_lookup: started.elapsed(),
                    ..Default::default()
                },
            );
            return Ok(report);
        }
        let mut all = options.clone();
        all.top_k = usize::MAX;
        // A conditional table is generated by the same live search; the E2
        // standalone disk catalog is not a source for these mixed-tier rows.
        all.bake_mode = crate::bake::BakeMode::Disabled;
        let report = search_manufacture_triples(pool, table, &all)?;
        let masks = report
            .top
            .iter()
            .map(|hit| {
                let mut mask = vec![0u64; operators.len().div_ceil(64)];
                for name in &hit.names {
                    let index = operators
                        .iter()
                        .position(|operator| operator.name == *name)
                        .expect("live response belongs to pool");
                    mask[index / 64] |= 1 << (index % 64);
                }
                mask
            })
            .collect();
        let response = ResponseTable {
            operators,
            skills: table.skills().to_vec(),
            options: ManuSearchOptions { layout, ..all },
            hits: report.top,
            masks,
        };
        let result = response.query(&response.operators, options, started);
        // Bounded storage changes reuse only, never the searched universe.
        if tables.len() == 16 {
            tables.remove(0);
        }
        tables.push(response);
        Ok(result)
    }
}

fn is_subsequence(needles: &[ManuOperator], haystack: &[ManuOperator]) -> bool {
    let mut next = 0;
    for operator in haystack {
        if needles.get(next).is_some_and(|wanted| {
            wanted.name == operator.name
                && wanted.elite == operator.elite
                && wanted.buff_ids == operator.buff_ids
                && wanted.tags == operator.tags
        }) {
            next += 1;
        }
    }
    next == needles.len()
}

impl ResponseTable {
    fn query(
        &self,
        operators: &[ManuOperator],
        options: &ManuSearchOptions,
        started: Instant,
    ) -> ManuSearchReport {
        let mut available = vec![0u64; self.operators.len().div_ceil(64)];
        for operator in operators {
            if let Some(index) = self
                .operators
                .iter()
                .position(|entry| entry.name == operator.name)
            {
                available[index / 64] |= 1 << (index % 64);
            }
        }
        let anchor = options.must_include_name.as_ref().and_then(|name| {
            self.operators
                .iter()
                .position(|operator| operator.name == *name)
        });
        let mut evaluated = 0;
        let mut top = Vec::new();
        let mut best = empty_hit();
        for (hit, mask) in self.hits.iter().zip(&self.masks) {
            if !mask
                .iter()
                .zip(&available)
                .all(|(row, available)| row & available == *row)
                || anchor.is_some_and(|index| mask[index / 64] & (1 << (index % 64)) == 0)
            {
                continue;
            }
            if evaluated == 0 {
                best = hit.clone();
            }
            evaluated += 1;
            if top.len() < options.top_k {
                top.push(hit.clone());
            }
        }
        let capacity = options.operator_capacity.clamp(1, 3);
        let combinations = if options.must_include_name.is_some() {
            n_choose_k_u64(operators.len().saturating_sub(1), capacity - 1)
        } else {
            n_choose_k_u64(operators.len(), capacity)
        };
        ManuSearchReport {
            recipe_mode: options.recipe_mode,
            best,
            top,
            combinations,
            evaluated,
            elapsed: started.elapsed(),
            gold_line: None,
            battle_record_line: None,
        }
    }
}

/// Remove only facts that the static manufacture interpreter cannot observe.
/// Retain all numeric fields, global resources and manufacturing injects.
fn cache_layout(
    base: &SharedLayout,
    operators: &[ManuOperator],
    table: &SkillTable,
) -> SharedLayout {
    let mut layout = (**base).clone();
    let mut in_base = HashSet::new();
    let mut in_power = HashSet::new();
    let mut in_trade = HashSet::new();
    let mut in_training = HashSet::new();
    for operator in operators {
        // Candidate projection deduplicates these names even without a
        // point-name skill, including the Rhine counter.
        in_base.insert(operator.name.as_str());
        for buff in &operator.buff_ids {
            if let Some(skill) = table.get(buff) {
                for atom in &skill.atoms {
                    match &atom.condition {
                        Some(Condition::OperatorInBase { name }) => {
                            in_base.insert(name);
                        }
                        Some(Condition::OperatorInPower { name }) => {
                            in_power.insert(name.as_str());
                        }
                        Some(Condition::OperatorInTrade { name }) => {
                            in_trade.insert(name.as_str());
                        }
                        Some(Condition::OperatorInTraining { name }) => {
                            in_training.insert(name.as_str());
                        }
                        _ => {}
                    }
                }
            }
        }
    }
    layout
        .base_workforce
        .retain(|name| in_base.contains(name.as_str()));
    layout
        .power_workforce
        .retain(|name| in_power.contains(name.as_str()));
    layout
        .trade_workforce
        .retain(|name| in_trade.contains(name.as_str()));
    layout
        .training_assist
        .retain(|name| in_training.contains(name.as_str()));
    layout
        .manu_workforce
        .retain(|name| operators.iter().any(|operator| operator.name == *name));
    for names in [
        &mut layout.base_workforce,
        &mut layout.power_workforce,
        &mut layout.trade_workforce,
        &mut layout.training_assist,
        &mut layout.manu_workforce,
    ] {
        names.sort();
        names.dedup();
    }
    layout.control_workforce.clear();
    layout.control_operators.clear();
    layout.control_buffs.clear();
    layout.trade_gold_line_sources.clear();
    layout.trade_tagged_count_sum.clear();
    layout.trade_stations_tagged_gte.clear();
    Arc::new(layout)
}
